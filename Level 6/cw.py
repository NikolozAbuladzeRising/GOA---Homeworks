# OUTPUT (გამოტანა) არის პროგრამის მიერ დამუშავებული ინფორმაციის მომხმარებლისთვის ჩვენება.
# მაგალითად, ეკრანზე ტექსტის გამოჩენა ან ხმის გამოცემა. პითონში ამისთვის ვიყენებთ print() ფუნქციას.


# ==========================================
# 2. რა არის კარგი პრაქტიკები (Best Practices)?
