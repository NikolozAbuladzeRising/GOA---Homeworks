# 2. Snake Case სტილი: პითონში რამდენიმე სიტყვიანი ცვლადები გამოიყოფა ქვედა ტირეთი (mag: first_name).
# 3. კომენტარები: რთული კოდის ნაწილები ყოველთვის უნდა აიხსნას მოკლე კომენტარით (#).
# 4. დაშორებები (Spaces): ოპერატორების გარშემო ვიყენებთ დაშორებებს (მაგ: x = 5 და არა x=5).
# 5. DRY პრინციპი (Don't Repeat Yourself): არ გაამეორო ერთი და იგივე კოდი ბევრჯერ.

# პრაქტიკული მაგალითი, სადაც დაცულია ეს წესები:
user_salary = 1500  # აზრიანი სახელი, snake_case და სწორი დაშორებები


